"""Conditional analysis: LP economics split by the pool's measured execution cost.

The headline run showed gross LP (fees - IL) is positive while total net is deeply
negative, with entry/exit cost as the dominant term. This asks the obvious next
question: is there a cost tier where the gross margin survives the round trip?

STATUS: this is a POST-HOC conditioning, generated by the R0 result. It is a
hypothesis, not a confirmed edge. Two reasons it cannot be promoted here:
  1. cost_bps comes from R2's single-block measurement near the panel end, so
     using it to select pools leaks a little future information.
  2. the tier is chosen after seeing the decomposition.
Any promotion requires a fresh pre-registration with point-in-time cost.
"""
import json, math, os, random
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "out")
ALPHA = 0.05 / 9
TIERS = [(0, 10), (10, 30), (30, 100), (100, 300), (300, 1e9)]


def mean(a): return sum(a) / len(a)


def median(a):
    s = sorted(a); k = len(s)
    return s[k // 2] if k % 2 else 0.5 * (s[k // 2 - 1] + s[k // 2])


def block_boot(byd, stat, n=4000, seed=7):
    rng = random.Random(seed)
    dates = list(byd)
    if len(dates) < 2:
        return stat([v for d in dates for v in byd[d]]), None, None
    out = []
    for _ in range(n):
        samp = []
        for _ in range(len(dates)):
            samp.extend(byd[dates[rng.randrange(len(dates))]])
        if samp:
            out.append(stat(samp))
    out.sort()
    return (stat([v for d in dates for v in byd[d]]),
            out[int(len(out) * ALPHA / 2)], out[int(len(out) * (1 - ALPHA / 2))])


def main():
    rows = json.load(open(os.path.join(OUT, "pnl.json")))

    print("=" * 118)
    print("GROSS LP MARGIN (fees - IL, before execution cost) and NET, by measured cost tier")
    print("=" * 118)
    print("%-4s %-5s %-12s %6s %6s %9s %9s %9s %9s %9s %8s"
          % ("T", "c", "cost_tier", "n", "pools", "fee", "il", "gross", "cost", "net", "win%"))
    keep = []
    for T in (1, 7, 30):
        for c in (0.5, 1.0, 2.0):
            for lo, hi in TIERS:
                g = [r for r in rows if r["T"] == T and r["c"] == c
                     and lo <= r["cost_bps"] < hi]
                if len(g) < 30:
                    continue
                fee = median([x["fee_bps"] for x in g])
                il = median([x["il_bps"] for x in g])
                cost = median([x["cost_bps_paid"] for x in g])
                net = median([x["net_bps"] for x in g])
                win = 100.0 * sum(1 for x in g if x["net_bps"] > 0) / len(g)
                npools = len({x["pool"] for x in g})
                tag = "%d-%d" % (lo, hi) if hi < 1e9 else "%d+" % lo
                print("%-4d %-5.1f %-12s %6d %6d %9.1f %9.1f %9.1f %9.1f %9.1f %8.1f"
                      % (T, c, tag, len(g), npools, fee, il, fee - il, cost, net, win))
                keep.append((T, c, tag, g))
        print("-" * 118)

    # For any tier/cell whose median net is positive, run the full statistics.
    print()
    print("=" * 118)
    print("CELLS WITH POSITIVE MEDIAN NET -> full block-bootstrap statistics")
    print("=" * 118)
    hits = []
    for T, c, tag, g in keep:
        if median([x["net_bps"] for x in g]) <= 0:
            continue
        byd = defaultdict(list)
        for r in g:
            byd[r["entry"]].append(r["net_bps"])
        mu, mlo, mhi = block_boot(byd, mean)
        md, _, _ = block_boot(byd, median, n=1500, seed=11)
        s = sorted(x["net_bps"] for x in g); k = max(1, int(len(s) * 0.005))
        trimmed = mean(s[k:-k]) if len(s) > 2 * k else mu
        npools = len({x["pool"] for x in g})
        nalts = len({x["alt"] for x in g})
        hits.append(dict(T=T, c=c, tier=tag, n=len(g), pools=npools, alts=nalts,
                         mean_bps=mu, mean_lo=mlo, mean_hi=mhi, median_bps=md,
                         trimmed_mean_bps=trimmed,
                         win_pct=100.0 * sum(1 for x in g if x["net_bps"] > 0) / len(g),
                         n_entry_dates=len(byd)))
        print("T=%-3d c=%-4.1f tier=%-9s n=%-6d pools=%-3d alts=%-3d dates=%-3d "
              "mean=%8.1f [%8.1f,%8.1f] median=%7.1f trimmed=%8.1f win=%.0f%%"
              % (T, c, tag, len(g), npools, nalts, len(byd), mu,
                 mlo if mlo is not None else float("nan"),
                 mhi if mhi is not None else float("nan"), md, trimmed,
                 100.0 * sum(1 for x in g if x["net_bps"] > 0) / len(g)))
    if not hits:
        print("(none)")

    # which alts actually carry the cheap tiers, and are they too few to trust?
    print()
    print("=" * 118)
    print("CONCENTRATION CHECK on the cheapest tier (cost < 30 bps), T=30")
    print("=" * 118)
    g = [r for r in rows if r["T"] == 30 and r["cost_bps"] < 30]
    per = defaultdict(list)
    for r in g:
        per[r["alt"]].append(r["net_bps"])
    print("%-12s %6s %10s %10s" % ("alt", "n", "med_net", "mean_net"))
    for a, v in sorted(per.items(), key=lambda x: -len(x[1])):
        print("%-12s %6d %10.1f %10.1f" % (a[:12], len(v), median(v), mean(v)))

    json.dump(hits, open(os.path.join(OUT, "cost_tier_hits.json"), "w"), indent=1)


if __name__ == "__main__":
    main()
