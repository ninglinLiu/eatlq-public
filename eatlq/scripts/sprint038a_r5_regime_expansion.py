#!/usr/bin/env python3
"""Sprint038A — Expand R5 canonical candidate CSVs for additional high-activity regimes.

Reads Sprint037A regime mining rationale; generates new candidates_{week}.csv via
scripts/sprint037b_r5_label_expansion.py (canonical CH ts-grid + QuoterV2 probes).

Downstream (optional phases): isolated Sprint037C multi-horizon labels into
mvp/audits/sprint038a/q4_multi_horizon/, then Sprint037G floor recompute into
mvp/audits/sprint038a/g037/.

No training, live, promotion, or supersession issuance.

Usage:
  LABEL_RPC_URL=... CLICKHOUSE_PASSWORD=... \\
    python3 scripts/sprint038a_r5_regime_expansion.py --phase all

  python3 scripts/sprint038a_r5_regime_expansion.py --phase selection
  python3 scripts/sprint038a_r5_regime_expansion.py --phase r5
  python3 scripts/sprint038a_r5_regime_expansion.py --phase sprint037c
  python3 scripts/sprint038a_r5_regime_expansion.py --phase sprint037g
"""

from __future__ import annotations

import argparse
import csv
import json
import os
import shutil
import subprocess
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[1]
SPRINT038A_DIR = REPO / "mvp/audits/sprint038a"
Q4_DIR = SPRINT038A_DIR / "q4_multi_horizon"
G037_DIR = SPRINT038A_DIR / "g037"
R5_DIR = REPO / "mvp/audits/sprint037b_r5"
REGIMES_JSON = SPRINT038A_DIR / "regimes_sprint037c.json"
SPRINT037A_SUMMARY = REPO / "mvp/diagnostics/sprint037a_regime_mining_summary.json"

# Core four already covered by canonical R5 before Sprint038A
EXISTING_CORE = ["2025-12-01", "2026-01-05", "2026-01-26", "2026-02-02"]

# Four non-overlapping high-activity weeks from sprint037a top_historical_regimes / weekly rollups
NEW_REGIMES = ["2025-12-29", "2026-02-23", "2026-03-02", "2026-03-30"]


def _week_end(week_start: str) -> str:
    d = datetime.strptime(week_start, "%Y-%m-%d").replace(tzinfo=timezone.utc)
    return (d + timedelta(days=7)).strftime("%Y-%m-%d")


def _log(msg: str) -> None:
    ts = datetime.now(timezone.utc).strftime("%H:%M:%S")
    print(f"[038a {ts}] {msg}", flush=True)


def _sub_env() -> dict[str, str]:
    """Child-process env: map Docker-internal CH hostnames to LAN bridge when needed."""
    e = os.environ.copy()
    if os.environ.get("SPRINT038A_CLICKHOUSE_URL"):
        e["CLICKHOUSE_URL"] = os.environ["SPRINT038A_CLICKHOUSE_URL"]
        return e
    ch = (e.get("CLICKHOUSE_URL") or "").lower()
    if "clickhouse" in ch and "172.18" not in ch:
        e["CLICKHOUSE_URL"] = "http://172.18.0.6:8123/"
    return e


def write_regime_selection_md() -> None:
    SPRINT038A_DIR.mkdir(parents=True, exist_ok=True)
    sprint037a = {}
    if SPRINT037A_SUMMARY.exists():
        sprint037a = json.loads(SPRINT037A_SUMMARY.read_text(encoding="utf-8"))

    top = sprint037a.get("top_historical_regimes") or []
    lines = [
        "# Sprint038A — regime selection (R5 expansion)",
        "",
        "Source: `mvp/diagnostics/sprint037a_regime_mining_summary.json` "
        "(activity-only ranking; not PnL, not alpha).",
        "",
        "## Already covered (core canonical R5)",
        "",
        "| week_start | note |",
        "|------------|------|",
    ]
    for w in sorted(EXISTING_CORE):
        lines.append(f"| {w} | existing `candidates_{w}.csv` |")

    lines += [
        "",
        "## New regimes added this sprint",
        "",
        "Criteria: high `total_swaps` / `dense_pools_ge_min`, disjoint week starts vs core four, "
        "within CH BF180 coverage window, suitable for CH block_number ts-grid.",
        "",
        "| week_start | rationale (Sprint037A) |",
        "|------------|-------------------------|",
    ]
    by_week = {str(x.get("week_start")): x for x in top if x.get("week_start")}
    for w in NEW_REGIMES:
        row = by_week.get(w, {})
        rank = row.get("rank", "—")
        swaps = row.get("total_swaps", "—")
        dense = row.get("dense_pools_ge_min", "—")
        lines.append(
            f"| {w} | top_historical rank **{rank}**; swaps={swaps}; dense_pools≥min={dense} |"
        )

    lines += [
        "",
        "## Sprint037C regime bundle",
        "",
        f"Eight-week JSON for isolated multi-horizon replay: `{REGIMES_JSON.relative_to(REPO)}`.",
        "",
        "---",
        "",
        "*Machine-generated by scripts/sprint038a_r5_regime_expansion.py*",
    ]
    out = SPRINT038A_DIR / "regime_selection.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    _log(f"Written {out}")


def run_r5_new_regimes() -> None:
    """Invoke canonical R5 generator per new week (requires LABEL_RPC_URL / CH)."""
    for w in NEW_REGIMES:
        _log(f"R5 --run --regime {w} …")
        cmd = [
            sys.executable,
            str(REPO / "scripts/sprint037b_r5_label_expansion.py"),
            "--run",
            "--no-global-artifacts",
            "--regime",
            w,
        ]
        r = subprocess.run(cmd, cwd=str(REPO), env=_sub_env())
        if r.returncode != 0:
            raise SystemExit(f"R5 failed for {w} exit={r.returncode}")
        cp = R5_DIR / f"candidates_{w}.csv"
        if not cp.exists():
            raise SystemExit(f"missing R5 output {cp}")
    _log("R5 expansion complete for all NEW_REGIMES")


def run_sprint037c_isolated() -> None:
    Q4_DIR.mkdir(parents=True, exist_ok=True)
    summary_path = SPRINT038A_DIR / "sprint037c_multi_horizon_summary.json"
    report_path = SPRINT038A_DIR / "sprint037c_report_expansion.md"
    cmd = [
        sys.executable,
        str(REPO / "scripts/sprint037c_multi_horizon.py"),
        "--run",
        "--r5-dir",
        str(R5_DIR.relative_to(REPO)),
        "--q4-out-dir",
        str(Q4_DIR.relative_to(REPO)),
        "--summary-json",
        str(summary_path.relative_to(REPO)),
        "--report-md",
        str(report_path.relative_to(REPO)),
        "--regimes-json",
        str(REGIMES_JSON.relative_to(REPO)),
    ]
    _log("Sprint037C isolated replay …")
    r = subprocess.run(cmd, cwd=str(REPO), env=_sub_env())
    if r.returncode != 0:
        raise SystemExit(f"Sprint037C failed exit={r.returncode}")


def run_sprint037g_isolated() -> None:
    G037_DIR.mkdir(parents=True, exist_ok=True)
    cmd = [
        sys.executable,
        str(REPO / "scripts/sprint037g_young_pool_onset_expansion.py"),
        "--q4-dir",
        str(Q4_DIR.relative_to(REPO)),
        "--audit-dir",
        str(G037_DIR.relative_to(REPO)),
        "--no-run-readouts",
    ]
    _log("Sprint037G floor recompute (isolated Q4 dir) …")
    r = subprocess.run(cmd, cwd=str(REPO), env=_sub_env())
    if r.returncode != 0:
        raise SystemExit(f"Sprint037G failed exit={r.returncode}")
    src = G037_DIR / "per_regime_floor_audit.csv"
    dst = SPRINT038A_DIR / "young_pool_onset_floor_audit.csv"
    if src.exists():
        shutil.copyfile(src, dst)
        _log(f"Copied floor audit → {dst}")


def _bool_csv(v: str | None) -> bool:
    return v in ("True", "true", "1")


def scan_r5_candidate_coverage(regime_weeks: list[str]) -> dict[str, Any]:
    per: dict[str, Any] = {}
    for w in regime_weeks:
        path = R5_DIR / f"candidates_{w}.csv"
        row: dict[str, Any] = {
            "week_start": w,
            "csv_exists": path.exists(),
            "ch_candidates": 0,
            "executable_candidates": 0,
            "labeled_rows": 0,
        }
        if not path.exists():
            per[w] = row
            continue
        ch = exe = lab = 0
        with path.open(newline="", encoding="utf-8") as f:
            for rec in csv.DictReader(f):
                ch += 1
                if _bool_csv(rec.get("entry_quote_ok")):
                    exe += 1
                if rec.get("rpc_label") not in (None, "", "None"):
                    lab += 1
        row["ch_candidates"] = ch
        row["executable_candidates"] = exe
        row["labeled_rows"] = lab
        per[w] = row

    return {
        "kind": "sprint038a_r5_candidate_expansion",
        "created_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "r5_dir": str(R5_DIR.relative_to(REPO)),
        "decision_flags": {
            "FAILED_NO_7D_ALPHA_ACTIVE": True,
            "TRAINING_ALLOWED": False,
            "TRAINING_REVIEW_ALLOWED": False,
            "NO_ALPHA_CLAIM": True,
            "RPC_BACKED_LABEL_VALIDATION_ALLOWED": True,
            "MULTI_HORIZON_RESEARCH_ALLOWED": True,
            "H12_ABLATION_ALLOWED": False,
            "PHASE6_ALLOWED": False,
            "LIVE_ALLOWED": False,
            "MODEL_PROMOTION_ALLOWED": False,
        },
        "regimes_order": regime_weeks,
        "per_regime": per,
    }


def scan_q4_counts(regime_weeks: list[str]) -> dict[str, int]:
    out: dict[str, int] = {}
    for w in regime_weeks:
        p = Q4_DIR / f"q4_candidates_{w}.csv"
        if not p.exists():
            out[w] = 0
            continue
        with p.open(encoding="utf-8") as fh:
            out[w] = max(0, sum(1 for _ in fh) - 1)
    return out


def write_r5_summary_json(regime_weeks: list[str]) -> dict[str, Any]:
    cov = scan_r5_candidate_coverage(regime_weeks)
    q4c = scan_q4_counts(regime_weeks)
    for w in regime_weeks:
        if w in cov["per_regime"]:
            cov["per_regime"][w]["q4_candidates"] = q4c.get(w, 0)

    g_sum_path = G037_DIR / "expansion_summary.json"
    young: dict[str, Any] = {}
    if g_sum_path.exists():
        young = json.loads(g_sum_path.read_text(encoding="utf-8"))

    cov["young_pool_onset_g037"] = {
        "strict_ok_grid_hits": young.get("stability_hits_strict_ok"),
        "grid_size": young.get("grid_size"),
        "baseline_strict_ok": young.get("baseline_strict_ok"),
        "stability_fraction": young.get("stability_fraction"),
        "min_holdout_per_regime": young.get("min_holdout_per_regime"),
    }
    cov["supersession_candidate"] = bool(young.get("supersession_readout_submitted"))

    out_path = SPRINT038A_DIR / "r5_candidate_expansion_summary.json"
    out_path.write_text(json.dumps(cov, indent=2), encoding="utf-8")
    _log(f"Written {out_path}")
    return cov


def write_run_readout(cov: dict[str, Any]) -> None:
    g37 = cov.get("young_pool_onset_g037") or {}
    hits = g37.get("strict_ok_grid_hits")
    grid = g37.get("grid_size")
    lines = [
        "# Run-038A — R5 regime expansion + isolated Sprint037C / Sprint037G floor",
        "",
        f"Generated: {cov.get('created_at')}",
        "",
        "## Selected regimes",
        "",
        "- **New R5 weeks:** " + ", ".join(NEW_REGIMES),
        "- **Sprint037C bundle:** see `mvp/audits/sprint038a/regimes_sprint037c.json`",
        "",
        "## R5 + Q4 coverage",
        "",
        "| week | CH cand | executable | labeled (R5) | Q4 rows |",
        "|------|---------|-------------|----------------|---------|",
    ]
    for w in cov.get("regimes_order") or []:
        pr = (cov.get("per_regime") or {}).get(w) or {}
        lines.append(
            f"| {w} | {pr.get('ch_candidates')} | {pr.get('executable_candidates')} | "
            f"{pr.get('labeled_rows')} | {pr.get('q4_candidates', '—')} |"
        )

    lines += [
        "",
        "## supersession_candidate",
        "",
        f"`supersession_candidate` = **{cov.get('supersession_candidate')}** "
        "(automated Sprint037G gate only; no formal Gate 0 issuance).",
        "",
        "## Young pool onset — strict grid",
        "",
        f"- strict_ok hits (27-cell grid): **{hits}** / **{grid}**",
        f"- baseline_strict_ok: **{g37.get('baseline_strict_ok')}**",
        f"- stability_fraction: **{g37.get('stability_fraction')}**",
        "",
        "Per-regime holdout floor (baseline cell): `young_pool_onset_floor_audit.csv`.",
        "",
        "## Decision flags",
        "",
        "```json",
        json.dumps(cov.get("decision_flags"), indent=2),
        "```",
        "",
        "`NO_ALPHA_CLAIM=true` — no formal supersession.",
        "",
        "---",
        "",
        "*Auto-generated by scripts/sprint038a_r5_regime_expansion.py*",
    ]
    p = REPO / "mvp/runs/run-038A-r5-expansion-readout.md"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("\n".join(lines) + "\n", encoding="utf-8")
    _log(f"Written {p}")


def main() -> None:
    parser = argparse.ArgumentParser(description="Sprint038A R5 regime expansion orchestrator")
    parser.add_argument(
        "--phase",
        choices=("selection", "r5", "sprint037c", "sprint037g", "summarize", "all"),
        default="all",
    )
    args = parser.parse_args()

    regime_weeks = sorted({r["week_start"] for r in json.loads(REGIMES_JSON.read_text(encoding="utf-8"))})

    if args.phase in ("selection", "all"):
        write_regime_selection_md()

    if args.phase in ("r5", "all"):
        run_r5_new_regimes()

    if args.phase in ("sprint037c", "all"):
        run_sprint037c_isolated()

    if args.phase in ("sprint037g", "all"):
        run_sprint037g_isolated()

    if args.phase in ("summarize", "all"):
        cov = write_r5_summary_json(regime_weeks)
        write_run_readout(cov)


if __name__ == "__main__":
    main()
